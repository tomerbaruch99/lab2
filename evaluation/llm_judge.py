"""
LLM-as-a-Judge for Answer Evaluation
=====================================

Uses Gemini to evaluate RAG answers against gold standard answers
with multiple quality metrics.
"""

import json
from typing import Dict

from gemini_integration import call_gemini


def build_judge_prompt(question: str, gold_answer: str, rag_answer: str) -> str:
    """
    Build a prompt for LLM to judge answer quality.
    
    Args:
        question: User question
        gold_answer: Correct answer from official documents
        rag_answer: Answer generated by RAG system
        
    Returns:
        Prompt string for the judge
    """
    return f"""
אתה בוחן איכות תשובות.

קיבלת:
שאלה:
\"\"\"{question}\"\"\"

תשובה נכונה (מתוך המסמך הרשמי):
\"\"\"{gold_answer}\"\"\"

תשובה שנוצרה על ידי המערכת (RAG):
\"\"\"{rag_answer}\"\"\"

הערך את התשובה של ה-RAG ביחס לתשובה הנכונה לפי המדדים הבאים (ציון 0 עד 1):

1. correctness - עד כמה התשובה נכונה עובדתית?
2. faithfulness - עד כמה התשובה נאמנה לתשובה הנכונה ולא ממציאה מידע?
3. completeness - עד כמה התשובה מכסה את החלקים החשובים בתשובה הנכונה?
4. conciseness - עד כמה התשובה ברורה ולא מיותרת?
5. overall - ציון כולל כללי.

החזר JSON בלבד בפורמט:
{{
  "correctness": <float>,
  "faithfulness": <float>,
  "completeness": <float>,
  "conciseness": <float>,
  "overall": <float>
}}
"""


def judge_answer(
    question: str,
    gold_answer: str,
    rag_answer: str,
    gemini_model
) -> Dict[str, float]:
    """
    Judge a RAG answer against a gold standard answer.
    
    Args:
        question: User question
        gold_answer: Correct answer from official documents
        rag_answer: Answer generated by RAG system
        gemini_model: Initialized Gemini model
        
    Returns:
        Dictionary with scores for correctness, faithfulness, completeness,
        conciseness, and overall (all 0.0-1.0)
    """
    prompt = build_judge_prompt(question, gold_answer, rag_answer)
    resp = call_gemini(gemini_model, prompt)
    
    try:
        data = json.loads(resp)
        return {
            "correctness": float(data.get("correctness", 0.0)),
            "faithfulness": float(data.get("faithfulness", 0.0)),
            "completeness": float(data.get("completeness", 0.0)),
            "conciseness": float(data.get("conciseness", 0.0)),
            "overall": float(data.get("overall", 0.0)),
        }
    except Exception as e:
        print(f"[WARN] LLM judge parsing error: {e}")
        return {
            "correctness": 0.0,
            "faithfulness": 0.0,
            "completeness": 0.0,
            "conciseness": 0.0,
            "overall": 0.0,
        }

